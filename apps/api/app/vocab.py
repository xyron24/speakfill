"""Yes/no vocabularies + spoken prompt builders (shared by the text loop and voice confirm)."""

import re

YES_WORDS: dict[str, set[str]] = {
    "en": {"yes", "yeah", "yep", "correct", "right", "sure", "okay", "ok"},
    "hi": {"haan", "han", "haan ji", "hanji", "sahi", "sahi hai", "theek", "theek hai", "ha"},
}

NO_WORDS: dict[str, set[str]] = {
    "en": {"no", "nope", "wrong", "incorrect", "not correct"},
    "hi": {"nahin", "nahi", "na", "galat", "galat hai", "mat"},
}


def match_yes_no(text: str, locale: str) -> bool | None:
    """True/False on a clear match, else None. Word-boundary matching (so 'know' != 'no')."""
    low = f" {text.lower().strip()} "
    yes_hits = any(re.search(rf"\b{re.escape(w)}\b", low) for w in YES_WORDS.get(locale, set()))
    no_hits = any(re.search(rf"\b{re.escape(w)}\b", low) for w in NO_WORDS.get(locale, set()))
    if yes_hits and not no_hits:
        return True
    if no_hits and not yes_hits:
        return False
    return None


def confirm_prompt(locale: str, readable: str) -> str:
    if locale == "hi":
        return f"मैंने सुना {readable}। सही है? हाँ या नहीं कहें।"
    return f"I heard {readable}. Correct? Say yes or no."


def retry_prompt(locale: str, ask: str, hint: str) -> str:
    if locale == "hi":
        return f"माफ़ कीजिए, वह समझ नहीं आया। {ask} {hint}".strip()
    return f"Sorry, I didn't catch that. {ask} {hint}".strip()


